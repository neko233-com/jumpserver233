import { test, expect, request } from "@playwright/test";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { writeFile } from "node:fs/promises";

const execute = promisify(execFile);
const base = process.env.JMS_REMOTE_QA_BASE_URL || "http://127.0.0.1:8083";
if (!/^http:\/\/127\.0\.0\.\d+:\d+$/.test(base)) throw Error("Remote account QA requires loopback isolation");
test.use({ locale: "en-US" });

test("remote Linux account lifecycle verifies encrypted keys, Web and CLI login, interrupted verification recovery and retained homes", async ({ browser }, info) => {
  test.setTimeout(180_000);
  const api = await request.newContext({ baseURL: base });
  const context = await browser.newContext({ locale: "en-US" });
  const page = await context.newPage();
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  const stamp = Date.now(), username = `remoteqa_${stamp.toString(36)}`, recoveryUser = `recoverqa_${stamp.toString(36)}`;
  let token = "", cookie = "", asset = "", hostName = "", allowAdded = false;
  const retain = process.env.JMS_REMOTE_QA_RETAIN === "true";
  const cli = async (args: string[]) => execute("go", ["run", "./cmd/jms", ...args], {
    cwd: fileURLToPath(new URL("../../server", import.meta.url)), timeout: 45_000,
    env: { ...process.env, JMS_SERVER_URL: base, JMS_TOKEN: token, JMS_ORG_ID: "", JMS_ACCOUNT: "", JMS_ACCESS_KEY_ID: "", JMS_ACCESS_KEY_SECRET: "" },
  });
  try {
    const admin = { username: process.env.JMS_REMOTE_QA_USERNAME || "e2e.admin", password: process.env.JMS_REMOTE_QA_PASSWORD || "synthetic-e2e-admin-password-2468" };
    let login = await api.post("/api/v1/authentication/auth/", { data: admin });
    if (!login.ok()) { await api.post("/api/v1/authentication/bootstrap", { data: admin }); login = await api.post("/api/v1/authentication/auth/", { data: admin }); }
    expect(login.ok()).toBe(true); token = (await login.json()).access_token;
    cookie = (await api.storageState()).cookies.map((c) => `${c.name}=${c.value}`).join("; ");
    await context.addCookies((await api.storageState()).cookies);
    const host = await (await api.get(process.env.JMS_REMOTE_QA_FIXTURE_URL || "http://127.0.0.1:12242/health")).json();
    hostName = host.container_name;
    expect(hostName).toMatch(/^jms233-keyhost-[a-f0-9-]{36}$/);
    const labels = JSON.parse((await execute("docker", ["inspect", "--format", "{{json .Config.Labels}}", hostName])).stdout);
    expect(labels["com.jumpserver233.qa.owner"]).toBe(host.owner);
    expect(host.owner === hostName || /^jumpserver233-e2e-/.test(host.owner)).toBe(true);
    expect(host.protection || host.account_admin).toBe(true);
    const name = `Remote Linux accounts ${stamp}`;
    const createdHost = await api.post("/api/v1/assets", { data: { name, host: process.env.JMS_REMOTE_QA_SSH_HOST || "127.0.0.1", port: Number(host.address.split(":").at(-1)), username: "root", password: host.protection ? "synthetic-protection-root-password-233" : "synthetic-account-admin-root-password-233", host_key_fingerprint: host.fingerprint } });
    expect(createdHost.status()).toBe(201); asset = (await createdHost.json()).id;
    const tasksPath = `/api/v1/assets/${asset}/remote-account-tasks`;
    const tasks = async () => (await (await api.get(tasksPath)).json()).results as Array<any>;
    const task = async (id: string) => (await tasks()).find((v) => v.operation.task.id === id);
    const completed = async (id: string) => expect.poll(async () => (await task(id))?.state, { timeout: 30_000 }).toBe("succeeded");
    const account = async (user: string) => (await (await api.get(`/api/v1/assets/${asset}/accounts?username=${user}`)).json()).results[0];
    const begin = async (action: string, user: string) => {
      const a = await account(user);
      const response = await api.post(tasksPath, { data: { action, username: user, ...(action === "create" ? { shell: "/bin/sh" } : { uid: a.remote_account.uid, account_id: a.id }), version: action === "create" ? (await (await api.get(`/api/v1/assets/${asset}/accounts`)).json()).version : a.version, request_id: crypto.randomUUID() } });
      expect(response.status()).toBe(201); return response.json();
    };
    await page.goto((process.env.JMS_REMOTE_QA_BASE_URL || "http://127.0.0.1:5177") + "/console");
    const row = page.getByRole("row").filter({ hasText: name });
    await row.getByText("More", { exact: true }).click();
    await row.getByRole("button", { name: "Managed accounts", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByRole("button", { name: "Remote Linux accounts", exact: true }).click();
    const panel = dialog.locator(".remote-accounts-panel");
    await panel.getByLabel("Remote username", { exact: true }).fill(username);
    await expect(panel.getByRole("button", { name: "Submit remote task", exact: true })).toBeEnabled();
    const createResponse = page.waitForResponse((r) => r.url().endsWith(tasksPath) && r.request().method() === "POST");
    await panel.getByRole("button", { name: "Submit remote task", exact: true }).click();
    expect((await createResponse).status()).toBe(201); const creation = (await tasks()).find((v) => v.operation.task.username === username && v.operation.task.action === "create"); await completed(creation.operation.task.id);
    const a = await account(username);
    expect(a.active).toBe(true); expect(a.key_rotation_enabled).toBe(true); expect(a.password_rotation_enabled).toBe(false);
    expect(a.remote_account.state).toBe("ready"); expect(a.key_fingerprint).toMatch(/^SHA256:/);
    expect(JSON.stringify(a)).not.toMatch(/PRIVATE KEY|synthetic-.*password/);
    const exec = JSON.parse((await cli(["--account", username, "exec", asset, "--json", "--", "id -un"])).stdout);
    expect(exec.stdout.trim()).toBe(username);
    await dialog.getByRole("button", { name: "Close", exact: true }).click();
    await row.getByText("More", { exact: true }).click();
    await row.getByRole("button", { name: "Managed accounts", exact: true }).click();
    await dialog.getByRole("row").filter({ hasText: username }).getByRole("button", { name: "Use account", exact: true }).click();
    let received = "";
    page.on("websocket", (socket) => {if(socket.url().includes("/terminal"))socket.on("framereceived", (frame) => {received += Buffer.isBuffer(frame.payload) ? frame.payload.toString("utf8") : frame.payload;});});
    await row.getByRole("button", { name: "Connect", exact: true }).click();
    const terminal = page.getByRole("dialog");
    await expect(terminal.locator(".ssh-terminal-status")).toHaveClass(/connected/);
    await terminal.locator(".xterm-helper-textarea").pressSequentially("printf 'REMOTE_WEB_%s\\n' \"$(id -un)\"\r");
    await expect.poll(()=>received).toContain("REMOTE_WEB_"+username);
    await terminal.getByRole("button", { name: "Close terminal", exact: true }).click();
    const disabled = JSON.parse((await cli(["--account", "root", "accounts", "remote-disable", asset, "--username", username])).stdout);
    await completed(disabled.operation.task.id); expect((await account(username)).active).toBe(false);
    expect((await execute("docker", ["exec", hostName, "getent", "passwd", username])).stdout).toContain("/usr/sbin/nologin");
    await row.getByText("More", { exact: true }).click(); await row.getByRole("button", { name: "Managed accounts", exact: true }).click();
    await dialog.getByRole("row").filter({ hasText: "root" }).getByRole("button", { name: "Use account", exact: true }).click();
    await row.getByText("More", { exact: true }).click(); await row.getByRole("button", { name: "Managed accounts", exact: true }).click();
    await dialog.getByRole("button", { name: "Remote Linux accounts", exact: true }).click();
    await panel.getByLabel("Remote action", { exact: true }).selectOption("enable"); await panel.getByLabel("Remote username", { exact: true }).fill(username);
    const enableResponse = page.waitForResponse((r) => r.url().endsWith(tasksPath) && r.request().method() === "POST");
    await panel.getByRole("button", { name: "Submit remote task", exact: true }).click(); expect((await enableResponse).status()).toBe(201); const enabled = (await tasks()).find((v) => v.operation.task.username === username && v.operation.task.action === "enable"); await completed(enabled.operation.task.id);
    expect((await account(username)).active).toBe(true);
    expect(JSON.parse((await cli(["--account", username, "exec", asset, "--json", "--", "id -un"])).stdout).stdout.trim()).toBe(username);
    const recovering = await begin("create", recoveryUser);
    await expect.poll(async () => (await task(recovering.operation.task.id))?.error_code, { timeout: 30_000 }).toBe("credential_verification_failed");
    expect((await account(recoveryUser)).active).toBe(false);
    const stagedFingerprint = (await account(recoveryUser)).key_fingerprint;
    expect((await execute("docker", ["exec", hostName, "getent", "passwd", recoveryUser])).stdout).toContain(recoveryUser);
    expect(recoveryUser).toMatch(/^recoverqa_[a-z0-9]+$/);
    await execute("docker", ["exec", hostName, "sh", "-ceu", 'sed -i "s/^AllowUsers .*/& $1/" /run/sshd_config_protection; kill -HUP "$(cat /run/keyhost.pid)"', "qa-allow", recoveryUser]); allowAdded = true;
    const pending = await task(recovering.operation.task.id);
    const inspected = JSON.parse((await cli(["accounts", "remote-attempt", asset, pending.operation.task.id, "--mode", "inspect", "--revision", String(pending.revision)])).stdout);
    await completed(inspected.operation.task.id); expect((await account(recoveryUser)).active).toBe(true);
    expect((await account(recoveryUser)).key_fingerprint).toBe(stagedFingerprint);
    const deletedRecovery = await begin("delete", recoveryUser); await completed(deletedRecovery.operation.task.id);
    const deleteResponse = page.waitForResponse((r) => r.url().endsWith(tasksPath) && r.request().method() === "POST");
    await panel.getByLabel("Remote action", { exact: true }).selectOption("delete"); await panel.getByLabel("Remote username", { exact: true }).fill(username);
    await panel.getByLabel("Repeat username to delete", { exact: true }).fill(username);
    await panel.getByRole("button", { name: "Submit remote task", exact: true }).click(); expect((await deleteResponse).status()).toBe(201); const deleted = (await tasks()).find((v) => v.operation.task.username === username && v.operation.task.action === "delete"); await completed(deleted.operation.task.id);
    expect(await account(username)).toBeUndefined(); expect(await account(recoveryUser)).toBeUndefined();
    for (const user of [username, recoveryUser]) expect((await execute("docker", ["exec", hostName, "stat", "-c", "%u:%a", `/home/${user}`])).stdout.trim()).toBe("0:700");
    await panel.getByRole("button", { name: "Refresh", exact: true }).click();
    await expect(panel).toContainText("Succeeded");
    await expect(panel.getByRole("alert")).toHaveCount(0);
    await panel.locator("summary").filter({hasText:"New remote operation"}).click();
    await page.screenshot({ path: info.outputPath("remote-accounts.en.png"), fullPage: true });
    await dialog.getByRole("button", { name: "中文", exact: true }).click();
    await expect(panel.getByRole("heading", { name: "远端 Linux 账号", exact: true })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("remote-accounts.zh-CN.png"), fullPage: true });
    await writeFile(info.outputPath("remote-result.json"), JSON.stringify({ asset, name, username, recoveryUser, fixture: hostName, encryptedKeys: true, keyVerifiedBeforeActivation: true, webSSH: true, cliSSH: true, recoveryAttempt: inspected.operation.attempt, retainedHome: "root:0700", retained: retain }));
    expect(errors).toEqual([]);
    if (!retain) expect((await api.delete(`/api/v1/assets/${asset}`)).status()).toBe(204);
  } finally {
    if (allowAdded) await execute("docker", ["exec", hostName, "sh", "-ceu", 'sed -i "s/ $1$//" /run/sshd_config_protection; kill -HUP "$(cat /run/keyhost.pid)"', "qa-revoke", recoveryUser]).catch(() => {});
    if (cookie) await fetch(base + "/api/v1/authentication/expire-session/", { method: "POST", headers: { Cookie: cookie, Origin: base }, signal: AbortSignal.timeout(5000) }).catch(() => {});
    if (token) await fetch(base + "/api/v1/authentication/expire-session/", { method: "POST", headers: { Authorization: `Bearer ${token}` }, signal: AbortSignal.timeout(5000) }).catch(() => {});
    await context.close(); await api.dispose();
  }
});
