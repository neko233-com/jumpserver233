import { test, expect, request } from "@playwright/test";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";
import { writeFile } from "node:fs/promises";

const execute = promisify(execFile);
const base = process.env.JMS_MANAGED_QA_BASE_URL || "http://127.0.0.1:8083";
if (!/^http:\/\/127\.0\.0\.\d+:\d+$/.test(base)) throw Error("Managed account QA requires loopback isolation");

test.use({ locale: "en-US" });
test("one host uses independent managed accounts across Web SSH, SFTP, CLI, rotation, gateway credentials and live revocation", async ({ page, browser }, info) => {
  test.setTimeout(180_000);
  const api = await request.newContext({ baseURL: base });
  const guestContext = await browser.newContext({ locale: "en-US" });
  const guest = await guestContext.newPage();
  const errors: string[] = [];
  page.on("pageerror", (e) => errors.push(e.message));
  guest.on("pageerror", (e) => errors.push(e.message));
  const stamp = Date.now(), username = `managedqa_${stamp.toString(36)}`;
  const remotePassword = "synthetic-managed-login-password-233";
  const retain = process.env.JMS_MANAGED_QA_RETAIN === "true";
  const fixtureURL = process.env.JMS_MANAGED_QA_FIXTURE_URL || "http://127.0.0.1:12242/health";
  let hostName = "", owner = "", createdUser = false, succeeded = false, sessionID = "";
  let adminToken = "", guestToken = "", adminCookie = "", guestCookie = "";
  const serverDir = fileURLToPath(new URL("../../server", import.meta.url));
  const verifyOwner = async () => {
    const labels = JSON.parse((await execute("docker", ["inspect", "--format", "{{json .Config.Labels}}", hostName])).stdout);
    expect(labels["com.jumpserver233.qa.owner"]).toBe(owner);
  };
  const cli = async (token: string, args: string[]) => execute("go", ["run", "./cmd/jms", ...args], {
    cwd: serverDir, timeout: 60_000,
    env: { ...process.env, JMS_SERVER_URL: base, JMS_TOKEN: token, JMS_ORG_ID: "", JMS_ACCOUNT: "", JMS_ACCESS_KEY_ID: "", JMS_ACCESS_KEY_SECRET: "" },
  });
  const expire = async (token: string, cookie: string) => {
    if (cookie) await fetch(base + "/api/v1/authentication/expire-session/", { method: "POST", headers: { Cookie: cookie, Origin: base }, signal: AbortSignal.timeout(5000) }).catch(() => {});
    if (token) await fetch(base + "/api/v1/authentication/expire-session/", { method: "POST", headers: { Authorization: `Bearer ${token}` }, signal: AbortSignal.timeout(5000) }).catch(() => {});
  };
  try {
    const admin = { username: process.env.JMS_MANAGED_QA_USERNAME || "e2e.admin", password: process.env.JMS_MANAGED_QA_PASSWORD || "synthetic-e2e-admin-password-2468" };
    let auth = await api.post("/api/v1/authentication/auth/", { data: admin });
    if (!auth.ok()) { await api.post("/api/v1/authentication/bootstrap", { data: admin }); auth = await api.post("/api/v1/authentication/auth/", { data: admin }); }
    expect(auth.ok()).toBe(true);
    adminToken = (await auth.json()).access_token;
    adminCookie = (await api.storageState()).cookies.map((c) => `${c.name}=${c.value}`).join("; ");
    await page.context().addCookies((await api.storageState()).cookies);
    const host = await (await api.get(fixtureURL)).json();
    hostName = host.container_name; owner = host.owner;
    expect(hostName).toMatch(/^jms233-keyhost-[a-f0-9-]{36}$/);
    expect(owner === hostName || /^jumpserver233-e2e-/.test(owner)).toBe(true);
    expect(username).toMatch(/^managedqa_[a-z0-9]+$/);
    await verifyOwner();
    await writeFile(info.outputPath("owned-managed-account.json"), JSON.stringify({ name: hostName, owner, username, retained: retain }));
    createdUser = true;
    await execute("docker", ["exec", hostName, "sh", "-ceu", 'useradd -m -s /bin/bash "$1"; printf "%s:%s\\n" "$1" "$2" | chpasswd; touch "/home/$1/managed-account-proof"; chown "$1:$1" "/home/$1/managed-account-proof"; printf "%s ALL=(root) NOPASSWD: /usr/sbin/chpasswd\n" "$1" > "/etc/sudoers.d/$1"; chmod 0440 "/etc/sudoers.d/$1"', "qa-create", username, remotePassword]);

    const gatewayResponse = await api.post("/api/v1/assets", { data: {
      name: `Managed gateway ${stamp}`, host: process.env.JMS_MANAGED_QA_SSH_HOST || "127.0.0.1", port: Number(host.address.split(":").at(-1)), username: "keyqa", password: "synthetic-keyhost-password-233", host_key_fingerprint: host.fingerprint,
    } });
    expect(gatewayResponse.status()).toBe(201);
    const gateway = (await gatewayResponse.json()).id;
    const gwPage = await (await api.get(`/api/v1/assets/${gateway}/accounts`)).json();
    const gwAccountResponse = await api.post(`/api/v1/assets/${gateway}/accounts`, { data: { username: "pluginqa", password: "synthetic-keyhost-password-233", version: gwPage.version } });
    expect(gwAccountResponse.status()).toBe(201);
    const gwAccount = await gwAccountResponse.json();
    const name = `Managed Linux SSH ${stamp}`;
    const targetResponse = await api.post("/api/v1/assets", { data: { name, host: "127.0.0.1", port: 22, username: "keyqa", password: "synthetic-keyhost-password-233", host_key_fingerprint: host.fingerprint, gateway_id: gwAccount.id } });
    expect(targetResponse.status()).toBe(201);
    const asset = (await targetResponse.json()).id;
    await page.goto("/console");
    const hostRow = page.getByRole("row").filter({ hasText: name });
    await hostRow.getByText("More", { exact: true }).click();
    await hostRow.getByRole("button", { name: "Managed accounts", exact: true }).click();
    const dialog = page.getByRole("dialog");
    await expect(dialog.getByRole("button", { name: "Add account", exact: true })).toBeEnabled();
    await dialog.getByRole("button", { name: "Add account", exact: true }).click();
    await dialog.getByLabel("Account username", { exact: true }).fill(username);
    await dialog.getByLabel("Display name", { exact: true }).fill("运维账号");
    await dialog.getByLabel("New password", { exact: true }).fill(remotePassword);
    const created = page.waitForResponse((r) => r.url().endsWith(`/api/v1/assets/${asset}/accounts`) && r.request().method() === "POST");
    await dialog.getByRole("button", { name: "Save", exact: true }).click();
    const createdResponse = await created;
    expect(createdResponse.status()).toBe(201);
    const createdAccounts = await (await api.get(`/api/v1/assets/${asset}/accounts?username=${username}`)).json();
    const account = createdAccounts.results[0];
    expect(createdAccounts.total).toBe(1);
    const endpoint = account.id;
    expect(account.asset_id).toBe(asset);
    expect(JSON.stringify(account)).not.toContain(remotePassword);
    expect(account.password_rotation_enabled).toBe(true);
    await expect(dialog.getByRole("row").filter({ hasText: username })).toBeVisible();
    await expect(dialog.getByLabel("New password", { exact: true })).toHaveCount(0);
    await dialog.getByRole("button", { name: "Close", exact: true }).click();

    const operator = { username: `managed.operator.${stamp}`, password: "synthetic-managed-platform-password-233" };
    const userResponse = await api.post("/api/v1/users", { data: { ...operator, role: "operator" } });
    expect(userResponse.status()).toBe(201);
    const user = (await userResponse.json()).id;
    await page.goto("/console/settings");
    await page.getByRole("tab", { name: "Asset grants", exact: true }).click();
    const grantForm = page.getByRole("main");
    await grantForm.getByRole("combobox", { name: "User", exact: true }).selectOption(user);
    await grantForm.getByRole("combobox", { name: "SSH asset and account", exact: true }).selectOption(asset);
    const grantScope = grantForm.getByRole("combobox", { name: "Grant scope type", exact: true });
    await grantScope.selectOption("node");
    await grantForm.getByRole("combobox", { name: "Asset account", exact: true }).fill("unconfigured-user");
    await grantScope.selectOption("asset");
    await expect(grantForm.getByRole("combobox", { name: "Asset account", exact: true })).toHaveValue("keyqa");
    await grantForm.getByRole("combobox", { name: "Asset account", exact: true }).selectOption(username);
    await grantForm.getByLabel("View asset and monitoring", { exact: true }).check();
    await grantForm.getByLabel("Connect over SSH", { exact: true }).check();
    await grantForm.getByLabel("SFTP file management", { exact: true }).check();
    const grantCreated = page.waitForResponse((r) => r.url().endsWith("/api/v1/grants") && r.request().method() === "POST");
    await grantForm.getByRole("button", { name: "Create", exact: true }).click();
    expect((await grantCreated).status()).toBe(201);
    const roleResponse = await api.post("/api/v1/rbac/roles", { data: { name: `Managed operation ${stamp}`, permissions: ["accounts.discover", "plugins.inspect"] } });
    expect(roleResponse.status()).toBe(201);
    const role = (await roleResponse.json()).id;
    expect((await api.put("/api/v1/rbac/bindings", { data: { subject_type: "user", subject_id: user, role_ids: [role] } })).status()).toBe(200);
    const guestAuth = await guest.request.post(base + "/api/v1/authentication/auth/", { data: operator });
    expect(guestAuth.ok()).toBe(true);
    guestToken = (await guestAuth.json()).access_token;
    guestCookie = (await guestContext.storageState()).cookies.map((c) => `${c.name}=${c.value}`).join("; ");
    const headers = { Authorization: `Bearer ${guestToken}` };
    const visible = await (await api.get("/api/v1/assets", { headers })).json();
    expect(visible).toHaveLength(1);
    expect(visible[0].id).toBe(asset);
    expect(visible[0].selected_account_id).toBe(endpoint);
    expect(visible[0].accounts).toHaveLength(1);
    expect((await api.post("/api/v1/sessions", { headers, data: { asset_id: asset } })).status()).toBe(403);
    await guest.goto("/console");
    const guestRow = guest.getByRole("row").filter({ hasText: name });
    await expect(guestRow).toContainText(username);
    await guestRow.getByText("More", { exact: true }).click();
    await guestRow.getByRole("button", { name: "Managed accounts", exact: true }).click();
    const chooser = guest.getByRole("dialog");
    await expect(chooser.getByRole("button", { name: "Add account", exact: true })).toHaveCount(0);
    await expect(chooser.getByRole("button", { name: "Edit", exact: true })).toHaveCount(0);
    await expect(chooser.getByRole("table")).not.toContainText("keyqa");
    await chooser.getByRole("button", { name: "Close", exact: true }).click();
    const who = await cli(guestToken, ["--account", username, "exec", asset, "--json", "--", "id -un"]);
    expect(JSON.parse(who.stdout).stdout.trim()).toBe(username);
    expect(who.stdout + who.stderr).not.toContain(remotePassword);
    await guest.goto("/workbench");
    const jobForm = guest.locator(".jobs-form");
    await jobForm.getByRole("combobox", { name: "Asset", exact: true }).selectOption(endpoint);
    await jobForm.getByRole("textbox", { name: "Command", exact: true }).fill("id -un");
    const jobCreated = guest.waitForResponse((r) => r.url().endsWith("/api/v1/ops/jobs") && r.request().method() === "POST");
    await jobForm.getByRole("button", { name: "Run command", exact: true }).click();
    const webJob = await (await jobCreated).json();
    expect(webJob.asset_id).toBe(endpoint);
    await expect.poll(async () => (await (await api.get(`/api/v1/ops/jobs/${webJob.id}`, { headers })).json()).stdout?.trim()).toBe(username);
    await guest.goto("/console");

    const listing = guest.waitForResponse((r) => r.url().includes(`/api/v1/assets/${endpoint}/files?`) && r.request().method() === "GET");
    await guestRow.getByRole("button", { name: "Files", exact: true }).click();
    const listingResponse = await listing;
    expect(listingResponse.status()).toBe(200);
    expect((await listingResponse.json()).entries.some((entry: { name: string }) => entry.name === "managed-account-proof")).toBe(true);
    await guest.getByRole("dialog").getByRole("button", { name: "Cancel", exact: true }).first().click();

    const rotated = await api.post(`/api/v1/assets/${endpoint}/password-rotation`);
    expect(rotated.status()).toBe(200);
    expect(JSON.stringify(await rotated.json())).not.toContain(remotePassword);
    expect(JSON.parse((await cli(guestToken, ["--account", username, "exec", asset, "--json", "--", "id -un"])).stdout).stdout.trim()).toBe(username);
    expect(JSON.parse((await cli(adminToken, ["exec", asset, "--json", "--", "id -un"])).stdout).stdout.trim()).toBe("keyqa");
    let current = await (await api.get(`/api/v1/assets/${asset}/accounts/${endpoint}`)).json();
    const keyResult = await api.post(`/api/v1/assets/${endpoint}/ssh-key-rotation`, { data: { request_id: crypto.randomUUID(), expected_revision: current.credential_revision } });
    expect(keyResult.status()).toBe(200);
    current = await (await api.get(`/api/v1/assets/${asset}/accounts/${endpoint}`)).json();
    expect(current.credential_type).toBe("ssh_key");
    expect(current.key_fingerprint).toMatch(/^SHA256:/);
    const keyPolicy = await api.put(`/api/v1/assets/${asset}/accounts/${endpoint}`, { data: { version: current.version, key_rotation_enabled: true } });
    expect(keyPolicy.status()).toBe(200);
    current = await keyPolicy.json();
    expect(current.key_rotation_enabled).toBe(true);
    const nextRotation = Date.parse(current.ssh_key_rotation.next_rotation_at);
    expect(nextRotation - Date.now()).toBeGreaterThan(6.9 * 24 * 3600_000);
    expect(JSON.parse((await cli(guestToken, ["--account", username, "exec", asset, "--json", "--", "id -un"])).stdout).stdout.trim()).toBe(username);
    const plugin = JSON.parse((await cli(guestToken, ["--account", username, "plugin", asset, "node_exporter", "detect", "--request-id", `managed-plugin-${stamp}`])).stdout);
    expect(plugin.state).toBe("succeeded");
    const collected = JSON.parse((await cli(guestToken, ["--account", username, "accounts", "discover", asset, "--request-id", `managed-discovery-${stamp}`])).stdout);
    expect(collected.state).toBe("succeeded");
    const discovered = await (await api.get(`/api/v1/assets/${asset}/discovered-accounts?limit=100`)).json();
    expect(discovered.source.asset_id).toBe(asset);
    expect(discovered.results.some((a: { username: string }) => a.username === username)).toBe(true);
    await page.goto("/console");
    const discoveredHost = page.getByRole("row").filter({ hasText: name });
    await discoveredHost.getByText("More", { exact: true }).click();
    await discoveredHost.getByRole("button", { name: "Collected accounts", exact: true }).click();
    await page.getByRole("dialog").getByRole("row").filter({ hasText: username }).getByRole("button", { name: "Manage account", exact: true }).click();
    const linkedDialog = page.getByRole("dialog");
    await linkedDialog.getByRole("row").filter({ hasText: username }).getByRole("button", { name: "Edit", exact: true }).click();
    await linkedDialog.getByRole("button", { name: "Save", exact: true }).click();
    await expect(linkedDialog).toContainText("Current discovery linked");
    expect((await (await api.get(`/api/v1/assets/${asset}/accounts/${endpoint}`)).json()).discovery_id).toBe(discovered.results.find((a: { username: string }) => a.username === username).id);
    await linkedDialog.getByRole("button", { name: "Close", exact: true }).click();
    const gatewayPrimary = await (await api.get(`/api/v1/assets/${gateway}/accounts/${gateway}`)).json();
    expect((await api.put(`/api/v1/assets/${gateway}/accounts/${gateway}`, { data: { version: gatewayPrimary.version, active: false } })).status()).toBe(200);
    expect(JSON.parse((await cli(guestToken, ["--account", username, "exec", asset, "--json", "--", "id -un"])).stdout).stdout.trim()).toBe(username);

    await guest.reload();
    let received = "";
    guest.on("websocket", (socket) => { if (socket.url().includes("/terminal")) socket.on("framereceived", (frame) => { received += Buffer.isBuffer(frame.payload) ? frame.payload.toString("utf8") : frame.payload; }); });
    const sessionCreated = guest.waitForResponse((r) => r.url().endsWith("/api/v1/sessions") && r.request().method() === "POST");
    await guest.getByRole("row").filter({ hasText: name }).getByRole("button", { name: "Connect", exact: true }).click();
    const sessionResponse = await sessionCreated;
    expect(sessionResponse.status()).toBe(201);
    sessionID = (await sessionResponse.json()).session_id;
    const terminal = guest.getByRole("dialog");
    await expect(terminal.locator(".ssh-terminal-status")).toHaveClass(/connected/);
    await terminal.locator(".xterm-helper-textarea").pressSequentially("id -un; printf 'PAM_%s\\n' READY\r");
    await expect.poll(() => received).toContain("PAM_READY");
    expect(received).toContain(username);
    current = await (await api.get(`/api/v1/assets/${asset}/accounts/${endpoint}`)).json();
    const disabled = await api.put(`/api/v1/assets/${asset}/accounts/${endpoint}`, { data: { version: current.version, active: false } });
    expect(disabled.status()).toBe(200);
    current = await disabled.json();
    await expect(terminal.locator(".ssh-terminal-status")).toHaveClass(/closed/, { timeout: 15_000 });
    expect((await api.post("/api/v1/sessions", { headers, data: { asset_id: endpoint } })).status()).toBe(404);
    const restored = await api.put(`/api/v1/assets/${asset}/accounts/${endpoint}`, { data: { version: current.version, active: true } });
    expect(restored.status()).toBe(200);
    expect(JSON.parse((await cli(guestToken, ["--account", username, "exec", asset, "--json", "--", "id -un"])).stdout).stdout.trim()).toBe(username);

    await page.reload();
    await page.getByRole("row").filter({ hasText: name }).getByText("More", { exact: true }).click();
    await page.getByRole("row").filter({ hasText: name }).getByRole("button", { name: "Managed accounts", exact: true }).click();
    const final = page.getByRole("dialog");
    const accountRow = final.getByRole("row").filter({ hasText: username });
    await expect(accountRow).toContainText("SSH private key");
    await accountRow.getByRole("button", { name: "Edit", exact: true }).click();
    await expect(final.getByLabel("SSH private key", { exact: true })).toHaveValue("");
    await final.getByRole("button", { name: "Cancel", exact: true }).click();
    await page.screenshot({ path: info.outputPath("managed-accounts.en.png") });
    await final.getByRole("button", { name: "中文", exact: true }).click();
    await expect(final).toContainText("托管账号");
    await page.screenshot({ path: info.outputPath("managed-accounts.zh-CN.png") });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.screenshot({ path: info.outputPath("managed-accounts.mobile.zh-CN.png") });
    expect(errors).toEqual([]);
    await writeFile(info.outputPath("managed-result.json"), JSON.stringify({ asset, name, account: endpoint, username, gateway, gatewayAccount: gwAccount.id, session: sessionID, retained: retain }));
    succeeded = true;
  } finally {
    if (sessionID && adminToken) await fetch(base + `/api/v1/sessions/${sessionID}`, { method: "DELETE", headers: { Authorization: `Bearer ${adminToken}` }, signal: AbortSignal.timeout(5000) }).catch(() => {});
    await expire(guestToken, guestCookie);
    await expire(adminToken, adminCookie);
    await guestContext.close();
    await api.dispose();
    if (createdUser && (!retain || !succeeded)) {
      await verifyOwner();
      await execute("docker", ["exec", hostName, "sh", "-ceu", 'if id "$1" >/dev/null 2>&1; then userdel -r "$1"; fi; rm -f "/etc/sudoers.d/$1"', "qa-remove", username]);
    }
  }
});
